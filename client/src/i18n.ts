export const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
}>({ lang: "en", setLang: () => {} });

export function useI18n() {
  const { lang, setLang } = useContext(LangContext);
  const t = (key: StringKey, vars?: Record<string, string | number>) => {
    let s: string = STRINGS[lang][key] ?? key;
    // Global replacement: a placeholder that appears twice must be filled
    // twice, not once (plain replace() only handles the first occurrence).
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
  /** Localize a client-error string ("[CODE] detail"). Unknown codes fall back
   *  to the detail; strings without a code (engine verbatim) pass through. */
  const tErr = (raw: string): string => {
    const m = /^\[([A-Z0-9_]+)\]\s*/.exec(raw);
    if (!m) return raw;
    const detail = raw.slice(m[0].length).trim();
    const key = ERROR_KEYS[m[1]];
    return key ? t(key, { detail }) : detail;
  };
  return { t, tErr, lang, setLang };
}
